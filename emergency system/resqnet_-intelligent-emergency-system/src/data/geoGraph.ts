// Helper to build realistic initial incident with priority computed
function createSeedIncident(
  id: string,
  incidentType: Incident['incidentType'],
  title: string,
  description: string,
  location: string,
  lat: number,
  lng: number,
  peopleAffected: number,
  severity: Incident['severity'],
  requiredResources: Incident['requiredResources'],
  status: Incident['status'],
  minutesAgo: number,
  assignedResourceIds: string[] = [],
  assignedHospitalId?: string
): Incident {
  const createdTime = new Date(Date.now() - minutesAgo * 60 * 1000).toISOString();
  const updatedTime = createdTime;

  const priorityBreakdown = computeIncidentPriority({
    severity,
    peopleAffected,
    incidentType,
    requiredResources,
    createdTime,
  });

  return {
    id,
    incidentType,
    title,
    description,
    location,
    latitude: lat,
    longitude: lng,
    peopleAffected,
    severity,
    requiredResources,
    status,
    priorityScore: priorityBreakdown.score,
    priorityBreakdown,
    assignedResourceIds,
    assignedHospitalId,
    createdTime,
    updatedTime,
    reportedBy: 'Metropolitan 911 Emergency Dispatch',
  };
}

